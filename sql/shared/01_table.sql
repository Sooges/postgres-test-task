CREATE TABLE t1 (
    id             bigint         GENERATED BY DEFAULT AS IDENTITY,
    op_date        timestamptz    NOT NULL DEFAULT now(),
    amount         numeric(18, 2) NOT NULL,
    state          smallint       NOT NULL DEFAULT 0,
    operation_guid uuid           NOT NULL DEFAULT gen_random_uuid(),
    message        jsonb          NOT NULL,
    CONSTRAINT t1_pkey PRIMARY KEY (id, op_date),
    CONSTRAINT t1_state_check CHECK (state IN (0, 1)),
    CONSTRAINT t1_message_check CHECK (
        message ? 'account'
        AND message ? 'client_id'
        AND message ->> 'op_type' IN ('online', 'offline')
    )
) PARTITION BY RANGE (op_date);

CREATE INDEX t1_operation_guid_idx ON t1 (operation_guid);

CREATE INDEX t1_pending_idx ON t1 (id) WHERE state = 0;

CREATE FUNCTION t1_create_partition(p_month date)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_start date := date_trunc('month', p_month)::date;
    v_from  timestamptz := v_start::timestamp AT TIME ZONE 'UTC';
    v_to    timestamptz := (v_start + interval '1 month') AT TIME ZONE 'UTC';
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS %I PARTITION OF t1 FOR VALUES FROM (%L) TO (%L)',
        't1_' || to_char(v_start, 'YYYY_MM'),
        v_from,
        v_to
    );
END;
$$;

CREATE FUNCTION t1_ensure_partitions(p_from date, p_to date)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_month date;
BEGIN
    FOR v_month IN
        SELECT generate_series(date_trunc('month', p_from), date_trunc('month', p_to), interval '1 month')::date
    LOOP
        PERFORM t1_create_partition(v_month);
    END LOOP;
END;
$$;
